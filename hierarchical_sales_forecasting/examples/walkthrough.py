# ===== PART B — WHITE-SPACE PLANNING (alternative philosophy) =========
# ======================================================================
# Up to Step 15 we used "earned planning" — historical signals drive the
# cascade, current pipeline drives reconciliation. Some orgs flip this:
# they plan around FORWARD-looking opportunity ("what can be achieved")
# and reconcile against HISTORICAL signals ("how have they actually
# performed against past targets"). Steps 16–17 show that flow on the
# same dataset, using NEW columns the analyst added to the same CSV.

# ======================================================================
# STEP 16 — Forward-looking cascade with a hard gate
# ======================================================================
section(16, "Cascade with FORWARD-looking metrics + a hard gate")
print("Forward-looking metrics: current installed seats (proportional),")
print("knowledge workers per territory (proportional), LTM expansion")
print("spend (inverse — high spend dampens upside). Gate: unmigrated")
print("seats == 0 means '$0 migration quota' — no white space, no target.\n")

# Build a fresh hierarchy that ALSO ingests the new forward columns
white_space_metrics_cols = metrics_cols + [
    'Current_Seats_ProductX', 'Knowledge_Workers_Count', 'Unmigrated_Seats',
]
hierarchy_ws = SalesHierarchy()
hierarchy_ws.from_dataframe(
    df, path_cols=taxonomy, metrics_cols=white_space_metrics_cols,
    brand_new_col='Is_Brand_New',
)
cascader_ws = QuotaCascader(hierarchy_ws)

# Forward-looking metric slate (no historical attainment here)
forward_metrics = [
    MetricSpec('Current_Seats_ProductX',  direction='proportional',
               weight=1.0, columns=['Current_Seats_ProductX']),
    MetricSpec('Knowledge_Workers_Count', direction='proportional',
               weight=0.7, columns=['Knowledge_Workers_Count']),
    MetricSpec('LTM_ExpansionSpent',      direction='inverse',
               weight=0.5, columns=['LTM_ExpansionSpent']),  # dampener
]
# Gate: territories with zero unmigrated seats must get $0
gate_metrics = [
    MetricSpec('Unmigrated_Seats', columns=['Unmigrated_Seats']),
]

ws_quotas = cascader_ws.cascade_quota(
    'Global_Corp', MACRO_TARGET,
    hedge_multiplier=1.05,
    metrics=forward_metrics,
    gate_metrics=gate_metrics,
    new_ic_attr='_is_brand_new',
)

ws_leaves = hierarchy_ws.get_leaves('Global_Corp')
ws_ic_total = sum(ws_quotas[ic] for ic in ws_leaves)
ws_gated_leaves = [ic for ic in ws_leaves if ic in cascader_ws.gated_nodes]
ws_zero_leaves = [ic for ic in ws_leaves if ws_quotas[ic] == 0]

print(f"\nWhite-space cascade summary:")
print(f"  Macro target:        ${MACRO_TARGET:>12,.2f}")
print(f"  Sum of IC quotas:    ${ws_ic_total:>12,.2f}")
print(f"  Gated IC nodes:      {len(ws_gated_leaves):>4d}  (got $0 — no white space)")
print(f"  Non-gated $0 ICs:    {len(ws_zero_leaves) - len(ws_gated_leaves):>4d}")
print(f"  Funded IC nodes:     {len([ic for ic in ws_leaves if ws_quotas[ic] > 0]):>4d}")

# Show that the whole APAC subtree under Mgr_Dir_RVP_APAC_1_1_1 is gated
mgr_with_zero_team = 'Mgr_Dir_RVP_APAC_1_1_1'
if mgr_with_zero_team in cascader_ws.gated_nodes:
    mgr_team_ics = hierarchy_ws.get_children(mgr_with_zero_team)
    print(f"\n  Whole-subtree gate propagation example:")
    print(f"    {mgr_with_zero_team} (entire team fully migrated): "
          f"${ws_quotas.get(mgr_with_zero_team, 0):,.2f}")
    for ic in mgr_team_ics[:3]:
        print(f"      └─ {ic}: ${ws_quotas[ic]:,.2f}")
    print(f"      ({len(mgr_team_ics)} ICs total — all $0)")

