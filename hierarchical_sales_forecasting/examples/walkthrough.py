# STEP 8 — Cascade with multi-metric blend + per-region hedge
# ======================================================================
section(8, "Cascade $50M with multi-metric blend + per-region hedge")
print("Hedge: NA aggressive 10%, EMEA + APAC standard 5%, Global 5%.")
