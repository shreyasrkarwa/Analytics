# STEP 10 — Diagnose pipeline health (multi-column pipeline)
# ======================================================================
section(10, "Diagnose pipeline coverage (sums 3 pipeline columns per IC)")
print("Pipeline = Open_Pipeline + Late_Stage_Commit + Best_Case_Adds.")
print("Per-region risk thresholds — NA aggressive, APAC conservative.\n")

adjuster = PipelineAdjuster(
    hierarchy,
    quotas,
    pipeline_attr=['Open_Pipeline', 'Late_Stage_Commit', 'Best_Case_Adds'],
)

coverage_thresholds = {
    'NA':       {'healthy': 1.5, 'at_risk': 0.8},
    'EMEA':     {'healthy': 2.5, 'at_risk': 1.2},
    'APAC':     {'healthy': 3.0, 'at_risk': 1.5},
    '_default': {'healthy': 2.0, 'at_risk': 1.0},
}
diagnosis = adjuster.diagnose(coverage_thresholds)

# Summary by risk status across the whole org
risk_summary = diagnosis.groupby('Risk_Status').agg(
    Nodes=('Node', 'count'),
    Total_Quota=('Cascaded_Quota', 'sum'),
    Total_Pipeline=('Pipeline', 'sum'),
).sort_values('Nodes', ascending=False).reset_index()

print("Risk-status summary across ALL hierarchy nodes:")
print(risk_summary.to_string(index=False,
                              formatters={'Total_Quota': '${:,.0f}'.format,
                                          'Total_Pipeline': '${:,.0f}'.format}))

# Drill into IC-level rows for a single manager
sample_mgr = list({list(hierarchy.graph.predecessors(ic))[0]
                   for ic in veterans})[0]
mgr_ics = hierarchy.get_children(sample_mgr)
print(f"\nIC-level coverage under {sample_mgr}:")
print(diagnosis[diagnosis['Node'].isin(mgr_ics)]
      [['Node', 'Cascaded_Quota', 'Pipeline', 'Coverage_Ratio', 'Risk_Status']]
      .to_string(index=False,
                 formatters={'Cascaded_Quota': '${:,.0f}'.format,
                             'Pipeline': '${:,.0f}'.format,
                             'Coverage_Ratio': '{:.2f}x'.format}))


# ======================================================================
# STEP 11 — Redistribute IC quotas based on pipeline coverage
# ======================================================================
section(11, "Redistribute IC quotas based on pipeline health (zero-sum)")
print("Within each manager: ICs with low pipeline coverage shed quota to")
print("ICs with high coverage, capped at ±20% per IC. Manager totals are")
print("preserved exactly.\n")

# Lock the strategic hire so they aren't touched by redistribution
adjusted = adjuster.adjust(
    mode='redistribute',
    coverage_thresholds=coverage_thresholds,
    max_adjustment_pct=0.20,
    locked_nodes={strategic_ic},
)

# Count adjustments
adjusted_count = sum(1 for ic in leaves
                     if abs(adjusted.get(ic, 0) - quotas.get(ic, 0)) > 0.01)
print(f"ICs whose quota was adjusted: {adjusted_count} of {len(leaves)}")

# Verify zero-sum per manager
manager_nodes = [n for n in hierarchy.graph.nodes
                 if list(hierarchy.graph.successors(n))
                 and all(hierarchy.graph.out_degree(c) == 0
                         for c in hierarchy.graph.successors(n))]
biggest_delta_mgr = max(manager_nodes, key=lambda m: abs(
    sum(adjusted[ic] - quotas[ic] for ic in hierarchy.get_children(m))
))
delta = sum(adjusted[ic] - quotas[ic]
            for ic in hierarchy.get_children(biggest_delta_mgr))
print(f"Largest manager-level drift (should be ~$0): "
      f"${delta:,.2f} at {biggest_delta_mgr}")

# Show a few movers
movers = sorted(
    [(ic, quotas[ic], adjusted[ic], adjusted[ic] - quotas[ic]) for ic in leaves
     if abs(adjusted[ic] - quotas[ic]) > 0.01],
    key=lambda t: abs(t[3]),
    reverse=True,
)[:5]
print(f"\nTop 5 ICs by absolute redistribution:")
print(f"  {'IC':<50s} {'Original':>14s} {'Adjusted':>14s} {'Delta':>12s}")
for ic, orig, adj, d in movers:
    print(f"  {ic:<50s} ${orig:>12,.0f} ${adj:>12,.0f} {'+'if d>=0 else ''}${d:>10,.0f}")


