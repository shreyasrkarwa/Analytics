# STEP 14 — Write outputs to a SQL database (SQLite example)
# ======================================================================
import sqlite3
section(14, "Write outputs to a SQL database (SQLite example)")
print("Every output is already a DataFrame, so pandas' built-in to_sql()")
print("handles writes to ANY SQLAlchemy-compatible database (SQLite,")
print("Postgres, MySQL, Snowflake, BigQuery, Redshift, etc). Here we")
print("demo with SQLite — same pattern works for production DBs.\n")

# Pick a writable location for the SQLite DB. On most local filesystems
# OUT_DIR works fine; some sandboxes / network mounts don't support
# SQLite's file-locking, so fall back to the system tempdir.
import tempfile
preferred_db_path = os.path.join(OUT_DIR, 'cascade_results.db')
fallback_db_path = os.path.join(tempfile.gettempdir(), 'cascade_results.db')

def _try_write_sqlite(target_path):
    if os.path.exists(target_path):
        os.remove(target_path)
    tables = {
        'cascaded_quotas':       cascaded_df,
        'normalized_weights':    cascader.weights_report,
        'pipeline_diagnosis':    diagnosis,
        'redistributed_quotas':  redist_df,
        'commit_reconciliation': recon_df,
    }
    with sqlite3.connect(target_path) as conn:
        for name, frame in tables.items():
            frame.to_sql(name, conn, if_exists='replace', index=False)
            n = conn.execute(f'SELECT COUNT(*) FROM {name}').fetchone()[0]
            print(f"  wrote {n:>4d} rows to table `{name}`")
    return target_path

try:
    db_path = _try_write_sqlite(preferred_db_path)
    print(f"\nDatabase: {db_path}")
except (sqlite3.OperationalError, OSError, PermissionError) as e:
    print(f"  ({preferred_db_path} not writable: {e}; falling back to tempdir)")
    db_path = _try_write_sqlite(fallback_db_path)
    print(f"\nDatabase: {db_path}  (fallback location)")

# Smoke-test: read one row back to prove it's queryable
print(f"\nSmoke-test query — region totals from cascaded_quotas:")
with sqlite3.connect(db_path) as conn:
    rows = conn.execute(
        "SELECT level, node_id, cascaded_quota, unhedged_quota "
        "FROM cascaded_quotas WHERE depth = 1 ORDER BY cascaded_quota DESC"
    ).fetchall()
    for level, node, cascaded, unhedged in rows:
        print(f"  {level:<8s} {node:<6s} cascaded ${cascaded:>14,.2f}  "
              f"unhedged ${unhedged:>14,.2f}")

print(f"\nFor Postgres / Snowflake / etc, swap the sqlite3 connection for a")
print(f"SQLAlchemy engine and the same to_sql() calls work unchanged:")
print(f"  from sqlalchemy import create_engine")
print(f"  engine = create_engine('postgresql://user:pass@host/db')")
print(f"  cascaded_df.to_sql('cascaded_quotas', engine, if_exists='replace')")


