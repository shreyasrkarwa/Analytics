# Pick a writable location for the SQLite DB. On most local filesystems
# OUT_DIR works fine; some sandboxes / network mounts don't support
# SQLite's file-locking, so fall back to the system tempdir.
import tempfile
preferred_db_path = os.path.join(OUT_DIR, 'cascade_results.db')
fallback_db_path = os.path.join(tempfile.gettempdir(), 'cascade_results.db')

def _try_write_sqlite(target_path):
    if os.path.exists(target_path):
        os.remove(target_path)
    tables = {
        'cascaded_quotas':       cascaded_df,
        'normalized_weights':    cascader.weights_report,
        'pipeline_diagnosis':    diagnosis,
        'redistributed_quotas':  redist_df,
        'commit_reconciliation': recon_df,
    }
    with sqlite3.connect(target_path) as conn:
        for name, frame in tables.items():
            frame.to_sql(name, conn, if_exists='replace', index=False)
            n = conn.execute(f'SELECT COUNT(*) FROM {name}').fetchone()[0]
            print(f"  wrote {n:>4d} rows to table `{name}`")
    return target_path

try:
    db_path = _try_write_sqlite(preferred_db_path)
    print(f"\nDatabase: {db_path}")
except (sqlite3.OperationalError, OSError, PermissionError) as e:
    print(f"  ({preferred_db_path} not writable: {e}; falling back to tempdir)")
    db_path = _try_write_sqlite(fallback_db_path)
    print(f"\nDatabase: {db_path}  (fallback location)")

