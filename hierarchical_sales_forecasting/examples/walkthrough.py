print(f"\nICs flagged brand-new via CSV: {len(flagged)}")
print(f"Examples: {flagged[:3]}")


# ======================================================================
# STEP 3 — Declare metrics with USER-PROVIDED direction
# ======================================================================
section(3, "Declare which metrics drive cascading + their direction")
print("Direction is a DOMAIN decision: the analyst tells the package whether")
print("more-of-X means MORE quota (proportional) or LESS quota (inverse).")
print("The package never overrides this from data.\n")

declared_metrics = [
    MetricSpec('NetNewACV',       direction='proportional', weight=1.0, lookback=4),
    MetricSpec('CloudSeats',      direction='proportional', weight=1.0, lookback=4),
    MetricSpec('DCSeats',         direction='inverse',      weight=1.0, lookback=4),
    MetricSpec('ExpansionSpent',  direction='inverse',      weight=1.0,
               columns=['LTM_ExpansionSpent']),
    MetricSpec('Has_Active_Cert', direction='proportional', weight=1.0, lookback=4),
]
for m in declared_metrics:
    print(f"  {m.name:<18s} direction={m.direction:<13s} "
          f"lookback={m.lookback}  columns={m.resolved_columns()}")


# ======================================================================
# STEP 4 — Suggest weights via correlation (directions stay user's)
# ======================================================================
section(4, "Suggest weights from data (correlation magnitude)")
print("Pass the declared MetricSpecs to suggest_weights. Each metric is")
print("correlated against NetNewACV_4Q_sum; |correlation| becomes the")
print("suggested weight. Directions are preserved exactly as declared.\n")

# Aggregate the per-quarter boolean cert columns into a single 4Q sum
# (range 0..4 per IC) so it correlates cleanly against the dollar target.
df['Has_Cert_4Q_sum'] = (
    df[['Q1_Has_Active_Cert', 'Q2_Has_Active_Cert',
        'Q3_Has_Active_Cert', 'Q4_Has_Active_Cert']]
    .astype(int).sum(axis=1)
)

# Direction is REQUIRED on every candidate. All 4 secondary metrics go
# through the suggester so each weight is grounded in the data.
# (NetNewACV is the cascade target itself — correlating it with itself
# would always give 1.0, so we pin it manually as the anchor.)
candidates = [
    {'name': 'CloudSeats',      'column': 'CloudSeats_4Q_sum',
     'direction': 'proportional', 'lookback': 4},
    {'name': 'DCSeats',         'column': 'DCSeats_4Q_sum',
     'direction': 'inverse',      'lookback': 4},
    {'name': 'ExpansionSpent',  'column': 'LTM_ExpansionSpent',
     'columns': ['LTM_ExpansionSpent'],
     'direction': 'inverse',      'lookback': 1},
    {'name': 'Has_Active_Cert', 'column': 'Has_Cert_4Q_sum',
     'direction': 'proportional', 'lookback': 4},
]

with warnings.catch_warnings(record=True) as warning_log:
    warnings.simplefilter('always')
    suggested, report = MetricSpec.suggest_weights(
        df,
        target_column='NetNewACV_4Q_sum',
        candidate_metrics=candidates,
    )

print("Suggested weights:")
for s in suggested:
    r = report[s.name]
    match_str = ('agrees' if r['direction_matches_data']
                 else 'DISAGREES — but user direction kept')
    print(f"  {s.name:<18s} direction={s.direction:<13s} "
          f"weight={s.weight:.3f}  corr={r['correlation']:+.3f}  ({match_str})")

if warning_log:
    print("\nWarnings emitted by suggest_weights:")
    for w in warning_log:
        print(f"  - {w.message}")
else:
    print("\nNo direction-mismatch warnings fired — data agrees with all directions.")


# ======================================================================
# STEP 5 — Override a suggested weight where domain knowledge disagrees
# ======================================================================
section(5, "Override a suggested weight (Pattern A: mutate after suggestion)")
print("Suppose DCSeats came back weak (0.067) but the RevOps team believes")
print("it's a more important headwind than the data shows for next quarter")
print("(maybe a known platform sunset). The analyst overrides just that")
print("weight — the rest stay data-driven.\n")

# Edit in place — suggested is a list of MetricSpec, fully mutable
for s in suggested:
    if s.name == 'DCSeats':
        before = s.weight
        s.weight = 0.4   # analyst's domain judgment
        print(f"  DCSeats weight: {before:.3f} (suggested) -> {s.weight:.3f} (overridden)")

# Pin the cascade target (NetNewACV) at the anchor weight of 1.0
cascade_metrics = [
    MetricSpec('NetNewACV', direction='proportional', weight=1.0, lookback=4),
    *suggested,
]

print("\nFinal cascade metric set:")
for m in cascade_metrics:
    print(f"  {m.name:<18s} direction={m.direction:<13s} weight={m.weight:.3f}")


