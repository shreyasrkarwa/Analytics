quotas_unhedged = dict(cascader.base_quotas)

leaves = hierarchy.get_leaves('Global_Corp')
ic_total = sum(quotas[ic] for ic in leaves)
print(f"Macro target:                ${MACRO_TARGET:>15,.2f}")
print(f"Sum of all IC quotas:        ${ic_total:>15,.2f}")
print(f"Compounded overassignment:   {(ic_total/MACRO_TARGET - 1)*100:>14.2f}%")
print(f"Number of ICs:               {len(leaves):>15d}")

print(f"\nPer-region totals at the RVP layer:")
for region in ['NA', 'EMEA', 'APAC']:
    region_total = quotas.get(region, 0.0)
    print(f"  {region:<6s} cascaded quota: ${region_total:,.2f}")

print(f"\nSample IC quotas (3 veteran + 3 brand-new):")
veterans = [n for n in leaves if not hierarchy.graph.nodes[n].get('_is_brand_new')][:3]
brand_new = [n for n in leaves if hierarchy.graph.nodes[n].get('_is_brand_new')][:3]
for ic in veterans + brand_new:
    flag = ' (BRAND-NEW)' if hierarchy.graph.nodes[ic].get('_is_brand_new') else ''
    print(f"  {ic:<55s} ${quotas[ic]:>12,.2f}{flag}")


