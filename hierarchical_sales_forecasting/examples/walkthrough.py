    raw_adj = current_commit * reconciler.bias_weights[mgr_id]
    blended = reconciler.reconcile_forecast(mgr_id, current_commit, ml_forecast)
    print(f"  {mgr_id}")
    print(f"     Manager committed:     ${current_commit:,.0f}")
    print(f"     Bias-adjusted human:   ${raw_adj:,.0f}")
    print(f"     Blended with ML:       ${blended:,.0f}")


