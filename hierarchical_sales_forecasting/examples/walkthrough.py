"""
Step-by-step walkthrough of b2b_revenue_forecasting (v0.3+).

Demonstrates every public capability end-to-end on the synthetic demo
dataset generated by examples/generate_demo_data.py:

  Step 1.  Load the CSV
  Step 2.  Build the hierarchy (with the brand-new IC column from CSV)
  Step 3.  Declare metrics + their direction (user input)
  Step 4.  Suggest weights from data (correlation magnitude)
  Step 5.  Override a suggested weight where domain disagrees
  Step 6.  Inspect the normalized-weights view (what stakeholders see)
  Step 7.  Sanity-check via exploratory direction inference
  Step 8.  Cascade quota with multi-metric blend + per-region hedge
  Step 9.  Add a CRO override + show how the carve-out interacts
  Step 10. Diagnose pipeline health (multi-column pipeline)
  Step 11. Redistribute IC quotas based on pipeline coverage
  Step 12. Reconcile manager commits with historical bias quotients
  Step 13. Export all outputs to CSV (with hedge audit columns)
  Step 14. Write outputs to a SQL database (SQLite example)
  Step 15. Generate an interactive HTML dashboard
  ── PART B: White-space planning (forward-looking cascade + gates) ──
  Step 16. Cascade with FORWARD-looking metrics + a hard gate
  Step 17. Reconcile using HISTORICAL attainment (instead of pipeline)
  Step 18. Summary report

Run from project root:
    python examples/walkthrough.py
"""
