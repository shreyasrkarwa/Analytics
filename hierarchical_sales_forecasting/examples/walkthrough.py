# STEP 11 — Redistribute IC quotas based on pipeline coverage
# ======================================================================
section(11, "Redistribute IC quotas based on pipeline health (zero-sum)")
print("Within each manager: ICs with low pipeline coverage shed quota to")
print("ICs with high coverage, capped at ±20% per IC. Manager totals are")
print("preserved exactly.\n")

# Lock the strategic hire so they aren't touched by redistribution
adjusted = adjuster.adjust(
    mode='redistribute',
    coverage_thresholds=coverage_thresholds,
    max_adjustment_pct=0.20,
    locked_nodes={strategic_ic},
)

# Count adjustments
adjusted_count = sum(1 for ic in leaves
                     if abs(adjusted.get(ic, 0) - quotas.get(ic, 0)) > 0.01)
print(f"ICs whose quota was adjusted: {adjusted_count} of {len(leaves)}")

# Verify zero-sum per manager
manager_nodes = [n for n in hierarchy.graph.nodes
                 if list(hierarchy.graph.successors(n))
                 and all(hierarchy.graph.out_degree(c) == 0
                         for c in hierarchy.graph.successors(n))]
biggest_delta_mgr = max(manager_nodes, key=lambda m: abs(
    sum(adjusted[ic] - quotas[ic] for ic in hierarchy.get_children(m))
))
delta = sum(adjusted[ic] - quotas[ic]
            for ic in hierarchy.get_children(biggest_delta_mgr))
print(f"Largest manager-level drift (should be ~$0): "
      f"${delta:,.2f} at {biggest_delta_mgr}")

# Show a few movers
movers = sorted(
    [(ic, quotas[ic], adjusted[ic], adjusted[ic] - quotas[ic]) for ic in leaves
     if abs(adjusted[ic] - quotas[ic]) > 0.01],
    key=lambda t: abs(t[3]),
    reverse=True,
)[:5]
print(f"\nTop 5 ICs by absolute redistribution:")
print(f"  {'IC':<50s} {'Original':>14s} {'Adjusted':>14s} {'Delta':>12s}")
for ic, orig, adj, d in movers:
    print(f"  {ic:<50s} ${orig:>12,.0f} ${adj:>12,.0f} {'+'if d>=0 else ''}${d:>10,.0f}")


